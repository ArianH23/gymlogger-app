-- Claude's entry point for writing a plan, plus an exercise order column on planned_sets.

alter table public.planned_sets add column exercise_position integer not null default 0;
comment on column public.planned_sets.exercise_position is
  'Order of the exercise inside the plan (1, 2, 3...). Show exercises sorted by this, then by set_no.';

-- generate_plan again, now filling exercise_position (otherwise unchanged).
create or replace function public.generate_plan(p_routine_id uuid) returns uuid
language plpgsql
set search_path = ''
as $$
declare
  v_user      uuid;
  v_plan_id   uuid := gen_random_uuid();
  re          record;
  v_n         integer;          -- how many past sessions exist for this exercise (max 2 looked at)
  v_w         numeric;          -- working weight last time (heaviest; lightest for assisted)
  v_w_prev    numeric;          -- same, session before
  v_ws        numeric[];        -- last session's weight per set (sets can use different weights)
  v_reps      integer[];        -- last session's reps_result per set
  v_set_w     numeric;
  v_fail1     boolean;          -- last session had a set below rep_min
  v_fail2     boolean;          -- ...and so did the session before
  v_inc       numeric;
  v_rule      text;             -- new | up | down | keep | repeat
  v_target_w  numeric;
  v_note      text;
  v_min       integer;
  v_max       integer;
  v_last      integer;
  k           integer;
  v_count     integer := 0;
  v_pos       integer := 0;     -- exercise order inside the plan
begin
  -- Under a logged-in user RLS hides other people's routines; the SQL editor / Claude connector has
  -- no auth.uid(), so the owner is taken from the routine itself.
  select r.user_id into v_user
  from public.routines r
  where r.id = p_routine_id and r.deleted_at is null;
  if v_user is null then
    raise exception 'routine % not found', p_routine_id;
  end if;

  -- A new rules plan replaces older pending rules plans (never a claude plan).
  update public.planned_sessions
     set status = 'superseded'
   where routine_id = p_routine_id and created_by = 'rules' and status = 'pending';

  insert into public.planned_sessions (id, user_id, routine_id, created_by, status, notes)
  values (v_plan_id, v_user, p_routine_id, 'rules', 'pending', 'Generated by the progression rules (generate_plan).');

  for re in
    select rx.target_sets, e.id as exercise_id, e.load_type, e.rep_min, e.rep_max, e.increment_kg
    from public.routine_exercises rx
    join public.exercises e on e.id = rx.exercise_id
    where rx.routine_id = p_routine_id and rx.deleted_at is null and e.deleted_at is null
    order by rx.position
  loop
    v_inc := re.increment_kg;
    v_pos := v_pos + 1;

    select count(distinct h.session_rank) into v_n
    from public.exercise_history(re.exercise_id, 2) h;

    select case when re.load_type = 'assisted' then min(h.weight_kg) else max(h.weight_kg) end
      into v_w from public.exercise_history(re.exercise_id, 2) h where h.session_rank = 1;
    select case when re.load_type = 'assisted' then min(h.weight_kg) else max(h.weight_kg) end
      into v_w_prev from public.exercise_history(re.exercise_id, 2) h where h.session_rank = 2;

    select array_agg(h.weight_kg order by h.set_no), array_agg(h.reps_result order by h.set_no)
      into v_ws, v_reps
    from public.exercise_history(re.exercise_id, 2) h
    where h.session_rank = 1;

    v_fail1 := exists (select 1 from public.exercise_history(re.exercise_id, 2) h
                       where h.session_rank = 1 and h.reps_result < re.rep_min);
    v_fail2 := exists (select 1 from public.exercise_history(re.exercise_id, 2) h
                       where h.session_rank = 2 and h.reps_result < re.rep_min);

    -- Pick the rule.
    if v_n = 0 then
      v_rule := 'new';
    elsif re.rep_max is not null
          and coalesce((select bool_and(r >= re.rep_max) from unnest(v_reps) r), false) then
      v_rule := 'up';                                   -- rule 1: every working set reached rep_max
    elsif re.load_type <> 'bodyweight' and v_n >= 2 and v_fail1 and v_fail2
          and v_w is not distinct from v_w_prev then
      v_rule := 'down';                                 -- rule 2: below rep_min in each of the last 2 sessions
    elsif re.rep_max is null then
      v_rule := 'repeat';                               -- no rep range set: repeat last time
    else
      v_rule := 'keep';                                 -- rule 3: same weight, +1 rep per set
    end if;

    -- Note (shown on the first set). Weights are decided per set below.
    v_note := null;
    if v_rule = 'new' then
      v_note := 'Establish load, stop 3 reps short of failure.';
    elsif v_rule = 'up' then
      if re.load_type = 'bodyweight' then
        v_note := 'All sets reached the top of the range: add load or a harder variation.';
      elsif v_inc is null then
        v_note := 'All sets reached the top of the range: raise the load (increment not set for this exercise).';
      elsif re.load_type = 'assisted' then
        v_note := format('All sets reached the top of the range: %s kg less assistance.', v_inc);
      else
        v_note := format('All sets reached the top of the range: +%s kg.', v_inc);
      end if;
    elsif v_rule = 'down' then
      if public.deload_weight(v_ws[1], v_inc, re.load_type = 'assisted') = v_ws[1] then
        v_note := 'Below the bottom of the range in each of the last 2 sessions, but 10% is less than one step: keeping the weight, aim for the bottom of the range.';
      else
        v_note := 'Below the bottom of the range in each of the last 2 sessions: about 10% lighter.';
      end if;
      if v_inc is null then
        v_note := v_note || ' Increment not set, rounded to 0.5 kg: check the available weights.';
      end if;
    elsif v_rule = 'repeat' then
      v_note := 'No rep range set for this exercise: repeating last time.';
    end if;

    -- One planned set per target set.
    for k in 1..re.target_sets loop
      v_last  := case when v_reps is null or cardinality(v_reps) = 0 then null
                      else v_reps[least(k, cardinality(v_reps))] end;
      v_set_w := case when v_ws is null or cardinality(v_ws) = 0 then null
                      else v_ws[least(k, cardinality(v_ws))] end;      -- each set keeps its own weight
      v_target_w := case v_rule
        when 'new'  then null
        when 'up'   then case when re.load_type = 'bodyweight' then null
                              when v_inc is null            then v_set_w
                              when re.load_type = 'assisted' then greatest(v_set_w - v_inc, 0)
                              else v_set_w + v_inc end
        when 'down' then public.deload_weight(v_set_w, v_inc, re.load_type = 'assisted')
        else v_set_w end;
      if v_rule = 'keep' then
        v_min := least(coalesce(v_last + 1, re.rep_min), re.rep_max);
        v_max := re.rep_max;
      elsif v_rule = 'repeat' then
        v_min := v_last;
        v_max := v_last;
      elsif v_rule = 'up' and (re.load_type = 'bodyweight' or v_inc is null) then
        v_min := re.rep_max;      -- nothing to add yet: stay at the top of the range
        v_max := re.rep_max;
      else                        -- new, up (with a weight step), down
        v_min := re.rep_min;
        v_max := re.rep_max;
      end if;

      insert into public.planned_sets (user_id, planned_session_id, exercise_id, exercise_position, set_no,
                                       target_weight_kg, target_reps_min, target_reps_max, note)
      values (v_user, v_plan_id, re.exercise_id, v_pos, k, v_target_w, v_min, v_max,
              case when k = 1 then v_note end);
      v_count := v_count + 1;
    end loop;
  end loop;

  if v_count = 0 then
    raise exception 'routine % has no exercises', p_routine_id;   -- rolls back the plan row too
  end if;
  return v_plan_id;
end;
$$;


-- submit_plan(routine_name, plan, notes): validate and insert a plan written by Claude, in one call.
-- plan is a JSON array, one entry per exercise, in the order it should be done:
--   [{"exercise": "Bench Press (Dumbbell)",
--     "sets": [{"weight_kg": 44, "reps_min": 7, "reps_max": 10, "note": "optional"}, ...]}, ...]
-- weight_kg may be omitted/null (bodyweight); reps_max defaults to reps_min. Sets are numbered by position.
-- Any exercise in the catalog is allowed, not only the routine's. Any error rolls back everything.
create function public.submit_plan(p_routine_name text, p_plan jsonb, p_notes text default null)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_routine   record;
  v_plan_id   uuid := gen_random_uuid();
  v_entry     jsonb;
  v_set       jsonb;
  v_name      text;
  v_ex_id     uuid;
  v_seen      uuid[] := '{}';
  v_pos       integer := 0;
  v_k         integer;
  v_w         numeric;
  v_rmin      numeric;
  v_rmax      numeric;
  v_sets      integer := 0;
begin
  select r.id, r.user_id into v_routine
  from public.routines r
  where lower(r.name) = lower(trim(p_routine_name)) and r.deleted_at is null;
  if not found then
    raise exception 'routine "%" not found. Available routines: %', p_routine_name,
      (select string_agg(r.name, ', ' order by r.position) from public.routines r where r.deleted_at is null);
  end if;

  if p_plan is null or jsonb_typeof(p_plan) <> 'array' or jsonb_array_length(p_plan) = 0 then
    raise exception 'plan must be a non-empty JSON array like [{"exercise": "...", "sets": [{"weight_kg": 40, "reps_min": 8, "reps_max": 12}]}]';
  end if;

  -- A new claude plan replaces older pending claude plans (never a rules plan).
  update public.planned_sessions
     set status = 'superseded'
   where routine_id = v_routine.id and created_by = 'claude' and status = 'pending';

  insert into public.planned_sessions (id, user_id, routine_id, created_by, status, notes)
  values (v_plan_id, v_routine.user_id, v_routine.id, 'claude', 'pending', p_notes);

  for v_entry in select * from jsonb_array_elements(p_plan) loop
    v_pos := v_pos + 1;
    v_name := v_entry ->> 'exercise';
    if v_name is null then
      raise exception 'plan item % has no "exercise" name', v_pos;
    end if;

    select e.id into v_ex_id
    from public.exercises e
    where lower(e.name) = lower(trim(v_name)) and e.user_id = v_routine.user_id and e.deleted_at is null;
    if v_ex_id is null then
      raise exception 'exercise "%" not found. Similar names: %', v_name,
        coalesce((select string_agg(s.name, '; ' order by s.name)
                  from (select e.name from public.exercises e
                        where e.user_id = v_routine.user_id and e.deleted_at is null
                          and exists (select 1 from unnest(string_to_array(lower(v_name), ' ')) w
                                      where length(w) > 3 and lower(e.name) like '%' || w || '%')
                        order by e.name limit 8) s), 'none; list them with: select name from exercises');
    end if;
    if v_ex_id = any (v_seen) then
      raise exception 'exercise "%" appears twice in the plan; put all its sets in one entry', v_name;
    end if;
    v_seen := v_seen || v_ex_id;

    if jsonb_typeof(v_entry -> 'sets') is distinct from 'array' or jsonb_array_length(v_entry -> 'sets') = 0 then
      raise exception 'exercise "%" needs a non-empty "sets" array', v_name;
    end if;

    v_k := 0;
    for v_set in select * from jsonb_array_elements(v_entry -> 'sets') loop
      v_k := v_k + 1;
      if v_set ? 'weight_kg' and jsonb_typeof(v_set -> 'weight_kg') not in ('number', 'null') then
        raise exception '%, set %: weight_kg must be a number or null', v_name, v_k;
      end if;
      if jsonb_typeof(v_set -> 'reps_min') is distinct from 'number'
         or (v_set ? 'reps_max' and jsonb_typeof(v_set -> 'reps_max') <> 'number') then
        raise exception '%, set %: reps_min (and reps_max if given) must be numbers', v_name, v_k;
      end if;
      v_w    := (v_set ->> 'weight_kg')::numeric;
      v_rmin := (v_set ->> 'reps_min')::numeric;
      v_rmax := coalesce((v_set ->> 'reps_max')::numeric, v_rmin);
      if v_w < 0 or v_rmin < 0 or v_rmax < v_rmin or v_rmin <> trunc(v_rmin) or v_rmax <> trunc(v_rmax) then
        raise exception '%, set %: need weight_kg >= 0, whole-number reps and reps_min <= reps_max', v_name, v_k;
      end if;

      insert into public.planned_sets (user_id, planned_session_id, exercise_id, exercise_position, set_no,
                                       target_weight_kg, target_reps_min, target_reps_max, note)
      values (v_routine.user_id, v_plan_id, v_ex_id, v_pos, v_k, v_w, v_rmin::integer, v_rmax::integer,
              v_set ->> 'note');
      v_sets := v_sets + 1;
    end loop;
  end loop;

  return jsonb_build_object('planned_session_id', v_plan_id, 'routine', p_routine_name,
                            'exercises', v_pos, 'sets', v_sets);
end;
$$;

comment on function public.submit_plan(text, jsonb, text) is
  'Claude writes the next session: submit_plan(routine name, JSON array of {exercise, sets:[{weight_kg, reps_min, reps_max, note}]}, notes). Validates names and numbers, replaces older pending claude plans, never touches rules plans. Returns the new plan id. Any error writes nothing.';

revoke execute on function public.submit_plan(text, jsonb, text) from public, anon;
grant  execute on function public.submit_plan(text, jsonb, text) to authenticated;
