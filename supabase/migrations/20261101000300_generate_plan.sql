-- Progression rules (double progression), shared by every client.
--   generate_plan(routine_id) writes a pending 'rules' plan for the routine and returns its id.

-- Round to the nearest multiple of the exercise's increment; with no increment, to the nearest 0.5 kg.
create function public.round_to_step(p_value numeric, p_step numeric) returns numeric
language sql immutable
set search_path = ''
as $$
  select case when p_step is null or p_step <= 0 then round(p_value * 2) / 2
              else round(p_value / p_step) * p_step end
$$;

-- Weight after a ~10% deload, rounded to the step. If the cut disappears in the rounding (10% is smaller
-- than one step, e.g. 7.5 kg with a 2.5 kg step) the weight is held rather than forced down a full step.
-- Assisted exercises go the other way: ~10% MORE assistance.
create function public.deload_weight(p_weight numeric, p_step numeric, p_assisted boolean) returns numeric
language sql immutable
set search_path = ''
as $$
  select case
    when p_weight is null then null
    when p_assisted then greatest(public.round_to_step(p_weight * 1.1, p_step), p_weight)
    else least(greatest(public.round_to_step(p_weight * 0.9, p_step), 0), p_weight)
  end
$$;

-- Working sets (no warm-ups) of the last p_sessions finished sessions that contained the exercise,
-- one row per set number. session_rank 1 = most recent. For left/right exercises the two sides are
-- merged and reps_result is the LOWER of the two (or the only side logged).
create function public.exercise_history(p_exercise_id uuid, p_sessions integer default 2)
returns table (session_rank integer, session_id uuid, started_at timestamptz,
               set_no integer, weight_kg numeric, reps_result integer)
language sql stable
set search_path = ''
as $$
  with recent as (
    select ss.id, ss.started_at, (row_number() over (order by ss.started_at desc))::integer as rnk
    from public.sessions ss
    where ss.deleted_at is null and ss.ended_at is not null
      and exists (select 1 from public.sets s
                  where s.session_id = ss.id and s.exercise_id = p_exercise_id
                    and s.deleted_at is null and not s.is_warmup)
    order by ss.started_at desc
    limit p_sessions
  )
  select r.rnk, r.id, r.started_at, s.set_no, max(s.weight_kg),
         case when bool_or(s.side is not null)
              then least(max(s.reps) filter (where s.side = 'L'), max(s.reps) filter (where s.side = 'R'))
              else max(s.reps) end
  from recent r
  join public.sets s on s.session_id = r.id and s.exercise_id = p_exercise_id
                    and s.deleted_at is null and not s.is_warmup
  group by r.rnk, r.id, r.started_at, s.set_no
$$;

create function public.generate_plan(p_routine_id uuid) returns uuid
language plpgsql
set search_path = ''
as $$
declare
  v_user      uuid;
  v_plan_id   uuid := gen_random_uuid();
  re          record;
  v_n         integer;          -- how many past sessions exist for this exercise (max 2 looked at)
  v_w         numeric;          -- working weight last time (heaviest; lightest for assisted)
  v_w_prev    numeric;          -- same, session before
  v_ws        numeric[];        -- last session's weight per set (sets can use different weights)
  v_reps      integer[];        -- last session's reps_result per set
  v_set_w     numeric;
  v_fail1     boolean;          -- last session had a set below rep_min
  v_fail2     boolean;          -- ...and so did the session before
  v_inc       numeric;
  v_rule      text;             -- new | up | down | keep | repeat
  v_target_w  numeric;
  v_note      text;
  v_min       integer;
  v_max       integer;
  v_last      integer;
  k           integer;
  v_count     integer := 0;
begin
  -- Under a logged-in user RLS hides other people's routines; the SQL editor / Claude connector has
  -- no auth.uid(), so the owner is taken from the routine itself.
  select r.user_id into v_user
  from public.routines r
  where r.id = p_routine_id and r.deleted_at is null;
  if v_user is null then
    raise exception 'routine % not found', p_routine_id;
  end if;

  -- A new rules plan replaces older pending rules plans (never a claude plan).
  update public.planned_sessions
     set status = 'superseded'
   where routine_id = p_routine_id and created_by = 'rules' and status = 'pending';

  insert into public.planned_sessions (id, user_id, routine_id, created_by, status, notes)
  values (v_plan_id, v_user, p_routine_id, 'rules', 'pending', 'Generated by the progression rules (generate_plan).');

  for re in
    select rx.target_sets, e.id as exercise_id, e.load_type, e.rep_min, e.rep_max, e.increment_kg
    from public.routine_exercises rx
    join public.exercises e on e.id = rx.exercise_id
    where rx.routine_id = p_routine_id and rx.deleted_at is null and e.deleted_at is null
    order by rx.position
  loop
    v_inc := re.increment_kg;

    select count(distinct h.session_rank) into v_n
    from public.exercise_history(re.exercise_id, 2) h;

    select case when re.load_type = 'assisted' then min(h.weight_kg) else max(h.weight_kg) end
      into v_w from public.exercise_history(re.exercise_id, 2) h where h.session_rank = 1;
    select case when re.load_type = 'assisted' then min(h.weight_kg) else max(h.weight_kg) end
      into v_w_prev from public.exercise_history(re.exercise_id, 2) h where h.session_rank = 2;

    select array_agg(h.weight_kg order by h.set_no), array_agg(h.reps_result order by h.set_no)
      into v_ws, v_reps
    from public.exercise_history(re.exercise_id, 2) h
    where h.session_rank = 1;

    v_fail1 := exists (select 1 from public.exercise_history(re.exercise_id, 2) h
                       where h.session_rank = 1 and h.reps_result < re.rep_min);
    v_fail2 := exists (select 1 from public.exercise_history(re.exercise_id, 2) h
                       where h.session_rank = 2 and h.reps_result < re.rep_min);

    -- Pick the rule.
    if v_n = 0 then
      v_rule := 'new';
    elsif re.rep_max is not null
          and coalesce((select bool_and(r >= re.rep_max) from unnest(v_reps) r), false) then
      v_rule := 'up';                                   -- rule 1: every working set reached rep_max
    elsif re.load_type <> 'bodyweight' and v_n >= 2 and v_fail1 and v_fail2
          and v_w is not distinct from v_w_prev then
      v_rule := 'down';                                 -- rule 2: below rep_min in each of the last 2 sessions
    elsif re.rep_max is null then
      v_rule := 'repeat';                               -- no rep range set: repeat last time
    else
      v_rule := 'keep';                                 -- rule 3: same weight, +1 rep per set
    end if;

    -- Note (shown on the first set). Weights are decided per set below.
    v_note := null;
    if v_rule = 'new' then
      v_note := 'Establish load, stop 3 reps short of failure.';
    elsif v_rule = 'up' then
      if re.load_type = 'bodyweight' then
        v_note := 'All sets reached the top of the range: add load or a harder variation.';
      elsif v_inc is null then
        v_note := 'All sets reached the top of the range: raise the load (increment not set for this exercise).';
      elsif re.load_type = 'assisted' then
        v_note := format('All sets reached the top of the range: %s kg less assistance.', v_inc);
      else
        v_note := format('All sets reached the top of the range: +%s kg.', v_inc);
      end if;
    elsif v_rule = 'down' then
      if public.deload_weight(v_ws[1], v_inc, re.load_type = 'assisted') = v_ws[1] then
        v_note := 'Below the bottom of the range in each of the last 2 sessions, but 10% is less than one step: keeping the weight, aim for the bottom of the range.';
      else
        v_note := 'Below the bottom of the range in each of the last 2 sessions: about 10% lighter.';
      end if;
      if v_inc is null then
        v_note := v_note || ' Increment not set, rounded to 0.5 kg: check the available weights.';
      end if;
    elsif v_rule = 'repeat' then
      v_note := 'No rep range set for this exercise: repeating last time.';
    end if;

    -- One planned set per target set.
    for k in 1..re.target_sets loop
      v_last  := case when v_reps is null or cardinality(v_reps) = 0 then null
                      else v_reps[least(k, cardinality(v_reps))] end;
      v_set_w := case when v_ws is null or cardinality(v_ws) = 0 then null
                      else v_ws[least(k, cardinality(v_ws))] end;      -- each set keeps its own weight
      v_target_w := case v_rule
        when 'new'  then null
        when 'up'   then case when re.load_type = 'bodyweight' then null
                              when v_inc is null            then v_set_w
                              when re.load_type = 'assisted' then greatest(v_set_w - v_inc, 0)
                              else v_set_w + v_inc end
        when 'down' then public.deload_weight(v_set_w, v_inc, re.load_type = 'assisted')
        else v_set_w end;
      if v_rule = 'keep' then
        v_min := least(coalesce(v_last + 1, re.rep_min), re.rep_max);
        v_max := re.rep_max;
      elsif v_rule = 'repeat' then
        v_min := v_last;
        v_max := v_last;
      elsif v_rule = 'up' and (re.load_type = 'bodyweight' or v_inc is null) then
        v_min := re.rep_max;      -- nothing to add yet: stay at the top of the range
        v_max := re.rep_max;
      else                        -- new, up (with a weight step), down
        v_min := re.rep_min;
        v_max := re.rep_max;
      end if;

      insert into public.planned_sets (user_id, planned_session_id, exercise_id, set_no,
                                       target_weight_kg, target_reps_min, target_reps_max, note)
      values (v_user, v_plan_id, re.exercise_id, k, v_target_w, v_min, v_max,
              case when k = 1 then v_note end);
      v_count := v_count + 1;
    end loop;
  end loop;

  if v_count = 0 then
    raise exception 'routine % has no exercises', p_routine_id;   -- rolls back the plan row too
  end if;
  return v_plan_id;
end;
$$;

comment on function public.generate_plan(uuid) is
  'Writes a pending plan (created_by = rules) for the routine from the progression rules and returns its id. Replaces older pending rules plans; never touches claude plans.';
comment on function public.exercise_history(uuid, integer) is
  'Working sets of the last N finished sessions containing an exercise (session_rank 1 = latest), one row per set number, L/R merged to the lower reps.';
comment on function public.deload_weight(numeric, numeric, boolean) is
  'About 10% lighter (10% more assistance for assisted), rounded to the step; held unchanged if the cut is smaller than one step.';
comment on function public.round_to_step(numeric, numeric) is
  'Rounds to the nearest multiple of the step; with a null step, to the nearest 0.5 kg.';

revoke execute on function public.generate_plan(uuid) from public, anon;
grant  execute on function public.generate_plan(uuid) to authenticated;
